static const Glyph* find_glyph(uint16_t codepoint) {
    for (size_t i = 0; i < sizeof(GLYPHS) / sizeof(GLYPHS[0]); i++) {
        if (GLYPHS[i].codepoint == codepoint) {
            return &GLYPHS[i];
        }
    }

    return NULL;
}

static void draw_glyph(uint8_t* framebuffer, int x, int y, uint16_t codepoint, uint8_t color) {
    const Glyph* glyph = find_glyph(codepoint);
    if (glyph == NULL) {
        glyph = find_glyph(' ');
    }

    for (int row = 0; row < 7; row++) {
        for (int col = 0; col < 5; col++) {
            if ((glyph->rows[row] >> (4 - col)) & 0x01) {
                epd_draw_pixel(x + col, y + row, color, framebuffer);
            }
        }
    }
}

static const char* decode_utf8(const char* text, uint16_t* codepoint) {
    unsigned char first = (unsigned char)text[0];
    if (first < 0x80) {
        *codepoint = first;
        return text + 1;
    }

    if ((first & 0xE0) == 0xC0) {
        unsigned char second = (unsigned char)text[1];
        if ((second & 0xC0) == 0x80) {
            *codepoint = (uint16_t)(((first & 0x1F) << 6) | (second & 0x3F));
            return text + 2;
        }
    } else if ((first & 0xF0) == 0xE0) {
        unsigned char second = (unsigned char)text[1];
        unsigned char third = (unsigned char)text[2];
        if (((second & 0xC0) == 0x80) && ((third & 0xC0) == 0x80)) {
            *codepoint = (uint16_t)(((first & 0x0F) << 12) | ((second & 0x3F) << 6) | (third & 0x3F));
            return text + 3;
        }
    }

    *codepoint = '?';
    return text + 1;
}

static void draw_text(uint8_t* framebuffer, int x, int y, const char* text, uint8_t color) {
    int cursor_x = x;
    int cursor_y = y;

    for (const char* p = text; *p != '\0';) {
        uint16_t codepoint = 0;
        const char* next = decode_utf8(p, &codepoint);

        if (codepoint == '\n') {
            cursor_x = x;
            cursor_y += 10;
            p = next;
            continue;
        }

        draw_glyph(framebuffer, cursor_x, cursor_y, codepoint, color);
        cursor_x += 6;
        p = next;
    }
}

static void draw_bitmap(
    uint8_t* framebuffer,
    const uint8_t* bitmap,
    int bitmap_width,
    int bitmap_height,
    int bitmap_x,
    int bitmap_y
) {
    if (bitmap == NULL || bitmap_width <= 0 || bitmap_height <= 0) {
        return;
    }

    for (int row = 0; row < bitmap_height; row++) {
        for (int col = 0; col < bitmap_width; col++) {
            epd_draw_pixel(
                bitmap_x + col,
                bitmap_y + row,
                bitmap[row * bitmap_width + col],
                framebuffer
            );
        }
    }
}

static int check_draw_error(enum EpdDrawError err) {
    if (err != EPD_DRAW_SUCCESS) {
        ESP_LOGE(TAG, "draw error: 0x%x", err);
        return (int)err;
    }

    return 0;
}

int papers3_display_init(void) {
    if (s_initialized) {
        return 0;
    }

    epd_init(&epd_board_m5papers3, &ED047TC2, EPD_LUT_64K);
    s_highlevel = epd_hl_init(EPD_BUILTIN_WAVEFORM);
    epd_set_rotation(s_rotation);

    epd_poweron();
    epd_clear();
    vTaskDelay(pdMS_TO_TICKS(500));
    epd_clear();
    epd_poweroff();

    s_initialized = true;
    return 0;
}

int papers3_display_set_rotation(int rotation_degrees) {
    int normalized = rotation_degrees % 360;
    if (normalized < 0) {
        normalized += 360;
    }

    switch (normalized) {
        case 0:
            s_rotation = EPD_ROT_PORTRAIT;
            break;
        case 90:
            s_rotation = EPD_ROT_LANDSCAPE;
            break;
        case 180:
            s_rotation = EPD_ROT_INVERTED_PORTRAIT;
            break;
        case 270:
            s_rotation = EPD_ROT_INVERTED_LANDSCAPE;
            break;
        default:
            return -1;
    }

    if (s_initialized) {
        epd_set_rotation(s_rotation);
    }

    return 0;
}

int papers3_display_render_scene(
    const char* text,
    const uint8_t* bitmap,
    int bitmap_width,
    int bitmap_height,
    int bitmap_x,
    int bitmap_y,
    int x,
    int y,
    int width,
    int height
) {
    if (!s_initialized) {
        int init_result = papers3_display_init();
        if (init_result != 0) {
            return init_result;
        }
    }

    uint8_t* framebuffer = epd_hl_get_framebuffer(&s_highlevel);
    epd_hl_set_all_white(&s_highlevel);

    EpdRect rect = {
        .x = x,
        .y = y,
        .width = width,
        .height = height,
    };

    epd_fill_rect(rect, 0xD0, framebuffer);
    epd_draw_rect(rect, 0x00, framebuffer);

    draw_text(framebuffer, x + 16, y + 16, text, 0x00);
    draw_bitmap(
        framebuffer,
        bitmap,
        bitmap_width,
        bitmap_height,
        bitmap_x,
        bitmap_y
    );

    epd_poweron();
    int temperature = (int)epd_ambient_temperature();
    int err = check_draw_error(epd_hl_update_screen(&s_highlevel, MODE_GC16, temperature));
    epd_poweroff();

    return err;
}

void papers3_display_deinit(void) {
    if (!s_initialized) {
        return;
    }

    epd_deinit();
    s_initialized = false;
}
